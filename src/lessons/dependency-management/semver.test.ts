describe('satisfies (npm semantics case table)', () => {
  it.each(INCLUDE)('%s includes %s', (range, version) => {
    expect(satisfies(version, range)).toBe(true);
  });
  it.each(EXCLUDE)('%s excludes %s', (range, version) => {
    expect(satisfies(version, range)).toBe(false);
  });
});

describe('what a range desugars to', () => {
  it.each([
    ['^1.4.2', '>=1.4.2 <2.0.0-0'],
    ['~1.4.2', '>=1.4.2 <1.5.0-0'],
    ['^0.3.1', '>=0.3.1 <0.4.0-0'],
    ['^0.0.3', '>=0.0.3 <0.0.4-0'],
    ['1.x', '>=1.0.0 <2.0.0-0'],
    ['>=1.2 <2', '>=1.2.0 <2.0.0-0'],
    ['1.2.3 - 2.3', '>=1.2.3 <2.4.0-0'],
    ['*', '*'],
    ['1.4.2', '1.4.2'],
  ])('%s means %s', (range, meaning) => {
    expect(explainRange(range)).toBe(meaning);
  });

  it('rejects nonsense', () => {
    expect(explainRange('^banana')).toBeNull();
  });
});

describe('versions', () => {
  it('orders pre-releases as the semver spec does', () => {
    const ordered = ['1.0.0-alpha', '1.0.0-alpha.1', '1.0.0-alpha.beta', '1.0.0-beta', '1.0.0-beta.2', '1.0.0-beta.11', '1.0.0-rc.1', '1.0.0', '1.0.1', '1.1.0', '2.0.0'];
    const parsed = ordered.map((s) => parseVersion(s)!);
    for (let i = 1; i < parsed.length; i++) expect(compare(parsed[i - 1], parsed[i])).toBeLessThan(0);
  });

  it('ignores build metadata and rejects malformed versions', () => {
    expect(compare(parseVersion('1.2.3+a')!, parseVersion('1.2.3+b')!)).toBe(0);
    for (const bad of ['1.2', '01.2.3', '1.2.3-', '1.0.0beta', 'x.y.z']) expect(parseVersion(bad)).toBeNull();
  });

  it('explains a miss: outside the bounds vs. an excluded pre-release', () => {
    expect(explainMatch('1.9.0', '^1.4.2')).toBe('match');
    expect(explainMatch('2.0.0', '^1.4.2')).toBe('outside');
    expect(explainMatch('1.5.0-beta.1', '^1.4.2')).toBe('prerelease');
    expect(explainMatch('1.5.0-beta.1', '^1.5.0-beta.1')).toBe('match');
    expect(explainMatch('1.0.0', 'nope')).toBe('invalid');
  });

  it('picks the highest match, not the first', () => {
    const list = ['1.4.2', '1.9.0', '1.4.9', '2.0.0', '1.10.0'];
    expect(maxSatisfying(list, '^1.4.2')).toBe('1.10.0');
    expect(maxSatisfying(list, '~1.4.2')).toBe('1.4.9');
    expect(maxSatisfying(list, '^3')).toBeNull();
  });
});
